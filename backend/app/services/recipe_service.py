_CATEGORY_PATTERNS = {}
for _cat_name, _keywords in _CATEGORY_KEYWORDS.items():
    _pattern = r'(?:^|\s|\W)(' + '|'.join(re.escape(k) for k in _keywords) + r')(?:\s|\W|$)'
    _CATEGORY_PATTERNS[_cat_name] = re.compile(_pattern, re.IGNORECASE)


def _categorize(ingredient: str) -> str:
    text = ' ' + _strip_accents(ingredient).lower() + ' '
    for cat, pattern in _CATEGORY_PATTERNS.items():
        if pattern.search(text):
            return cat
    return "Otros"


