def _normalize(ingredient: str) -> str:
    normalized = unicodedata.normalize('NFD', ingredient.strip().lower())
    normalized = ''.join(c for c in normalized if unicodedata.category(c) != 'Mn')
    normalized = re.sub(r"[^a-z0-9\s]", "", normalized)
    return normalized.strip()


def _strip_accents(text: str) -> str:
    normalized = unicodedata.normalize('NFD', text)
    return ''.join(c for c in normalized if unicodedata.category(c) != 'Mn')


def _clean_ingredient_name(raw: str) -> str:
    cleaned = html.unescape(raw.strip())
    if not cleaned:
        return ""
    cleaned = cleaned.lower()
    prev = None
    while cleaned != prev:
        prev = cleaned
        cleaned = re.sub(r'^\(\d[\d\s/]*\.?\d*\s*[^)]*\)\s*', '', cleaned)
        cleaned = re.sub(r'^(?:\.?\d+[\d/\-]*\.?\d*\s*)?', '', cleaned)
    units = re.compile(
        r'\b(?:cups?|tbsp|tsp|tablespoons?|teaspoons?|ounces?|oz|lbs?|pounds?|grams?|kg|g|ml|l|cloves?|pinches?|dashes?|cans?|packages?|jars?|bottles?|slices?|pieces?|sprigs?|stalks?|leaves?|cloves?|whole|large|medium|small|big|to taste|as needed|finely|thinly|diced|chopped|minced|sliced|optional|divided|plus|more|extra)\s+',
        re.IGNORECASE
    )
    cleaned = units.sub('', cleaned)
    if ',' in cleaned:
        cleaned = cleaned.split(',')[0].strip()
    cleaned = re.sub(r'^[%"\']+\s*', '', cleaned)
    cleaned = re.sub(r'\s+', ' ', cleaned).strip()
    if not cleaned or len(cleaned) < 2:
        cleaned = raw.strip().lower()
        cleaned = re.sub(r'\s+', ' ', cleaned).strip()
    translated = _TRANSLATIONS.get(cleaned)
    if translated:
        return translated
    return cleaned


